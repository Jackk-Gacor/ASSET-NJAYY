// Helper accessors
export function getDocumentsByNodeId(nodeId: string): DocumentMetadata[] {
  return MOCK_DOCUMENT_METADATA.filter(doc => doc.relatedNodeId === nodeId);
}

export function getDocumentsBySegmentId(segmentId: string): DocumentMetadata[] {
  return MOCK_DOCUMENT_METADATA.filter(doc => doc.relatedSegmentId === segmentId);
}

export function searchDocuments(
  query: string,
  typeFilter?: TechnicalDocumentType | 'ALL'
): DocumentMetadata[] {
  const cleanQ = query.toLowerCase().trim();
  return MOCK_DOCUMENT_METADATA.filter(doc => {
    const matchType = !typeFilter || typeFilter === 'ALL' || doc.type === typeFilter;
    const matchQ =
      !cleanQ ||
      doc.name.toLowerCase().includes(cleanQ) ||
      doc.id.toLowerCase().includes(cleanQ) ||
      (doc.description && doc.description.toLowerCase().includes(cleanQ)) ||
      (doc.region && doc.region.toLowerCase().includes(cleanQ)) ||
      (doc.relatedNodeId && doc.relatedNodeId.toLowerCase().includes(cleanQ)) ||
      (doc.relatedSegmentId && doc.relatedSegmentId.toLowerCase().includes(cleanQ));
    return matchType && matchQ;
  });
}
